// Post-processes the exported web index.html with the viewport armor DB Cam
// Mobile ships (proven on the crew's iPhones). Without maximum-scale=1 /
// user-scalable=no, iOS Safari AUTO-ZOOMS the page when an input with a
// font under 16px is focused — and stays zoomed. A zoomed page splits the
// visual viewport from the layout viewport, which is exactly what broke the
// camera: preview letterboxed or running off the bottom of the screen, and
// tap targets landing away from their pixels. The fixed body stops iOS
// rubber-band panning of the page itself.
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const path = "public/index.html";
let html = readFileSync(path, "utf8");

html = html.replace(
  /<meta name="viewport"[^>]*\/?>/,
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />',
);

if (!html.includes("dbco-lock")) {
  html = html.replace(
    "</head>",
    '<style id="dbco-lock">body{position:fixed;inset:0;width:100%;overscroll-behavior:none}</style>\n</head>',
  );
}

// Home-screen identity: the app installs as "DB Close Out" with the DB icon.
// assets/app-icon/icon.png is the single source (its SVG lives next to it);
// swap that file to change the icon everywhere.
copyFileSync("assets/app-icon/icon.png", "public/app-icon.png");
writeFileSync(
  "public/manifest.json",
  JSON.stringify(
    {
      name: "DB Close Out",
      short_name: "DB Close Out",
      start_url: "/",
      display: "standalone",
      background_color: "#1747A5",
      theme_color: "#143A75",
      icons: [{ src: "/app-icon.png", sizes: "1024x1024", type: "image/png", purpose: "any maskable" }],
    },
    null,
    2,
  ) + "\n",
);
html = html.replace(/<title>[^<]*<\/title>/, "<title>DB Close Out</title>");
if (!html.includes("apple-touch-icon")) {
  html = html.replace(
    "</head>",
    '<link rel="manifest" href="/manifest.json">\n' +
      '<link rel="apple-touch-icon" href="/app-icon.png">\n' +
      '<link rel="icon" type="image/png" href="/app-icon.png">\n' +
      '<meta name="apple-mobile-web-app-capable" content="yes">\n' +
      '<meta name="apple-mobile-web-app-title" content="DB Close Out">\n' +
      '<meta name="apple-mobile-web-app-status-bar-style" content="default">\n' +
      "</head>",
  );
}

// Service worker: the app shell (index, the hashed bundle, icons, assets)
// is cached on install, so a cold open with no signal still opens the app
// instead of a browser error page — which is what "Sin señal, todo se
// guarda" has been promising. JobTread data is never cached here (the app
// keeps its own copy) and every other origin (Google sign-in, uploads,
// maps) goes straight through. The list is written at build time because
// the bundle name changes with every export.
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}
const shellFiles = walk("public")
  .map((f) => "/" + relative("public", f).split("\\").join("/"))
  .filter((f) => f !== "/sw.js" && f !== "/metadata.json")
  .sort();
const version = createHash("sha1")
  .update(shellFiles.map((f) => `${f}:${statSync(join("public", f)).size}`).join("\n"))
  .digest("hex")
  .slice(0, 12);
const sw = `// GENERATED by scripts/fix-web-html.mjs — do not edit. Rebuild: npm run build:web
const VERSION = ${JSON.stringify(version)};
const CACHE = "dbco-shell-" + VERSION;
const SHELL = ${JSON.stringify(shellFiles.map((f) => encodeURI(f)))};
// JobTread data and auth: never served from this cache.
const API = /^\\/(health|auth|translate|transcribe|queue|jobs|tasks|webhooks)(\\/|$)/;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (API.test(url.pathname)) return;

  // The page itself: fresh when there is signal, the cached copy when not.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put("/index.html", copy));
          }
          return response;
        })
        .catch(() => caches.match("/index.html")),
    );
    return;
  }

  // Bundle, icons, assets: hashed names, so the cache is always right.
  event.respondWith(
    caches.match(request).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
writeFileSync("public/sw.js", sw);

if (!html.includes("serviceWorker")) {
  html = html.replace(
    "</body>",
    '<script>if ("serviceWorker" in navigator) { window.addEventListener("load", () => { navigator.serviceWorker.register("/sw.js").catch(() => {}); }); }</script>\n</body>',
  );
}

writeFileSync(path, html);
console.log(
  `public/index.html: viewport pinned, body locked, DB Close Out icon + manifest; sw.js ${version} caches ${shellFiles.length} shell files`,
);
